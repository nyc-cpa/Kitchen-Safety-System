/**
  * @brief  SysTick 中断处理 —— FreeRTOS 的节拍（tick）入口。
  *
  * 【为什么必须要有这个函数】
  *   本工程原先使用 CMSIS-RTOS2 包装层，cmsis_os2.c 内部用 #undef 取消了
  *   CMSIS 的弱定义并自行实现了 SysTick_Handler（内部调用 xPortSysTickHandler）。
  *   该文件已从工程移除（它强制 configMAX_PRIORITIES=56 等，占用较多 RAM），
  *   因此必须在此显式提供本函数，否则链接器会退回启动文件里的弱定义
  *   “SysTick_Handler: B .”（空死循环）—— 表现为 SysTick 一响就死循环，
  *   xTickCount 永不增加、vTaskDelay 永不返回、所有任务冻结（OLED 黑屏）。
  *
  * @note   configUSE_TICKLESS_IDLE 为 0（默认），因此直接转调即可。
  */
extern void xPortSysTickHandler(void);

void SysTick_Handler(void)
{
  /* USER CODE BEGIN SysTick_IRQn 0 */

  /* USER CODE END SysTick_IRQn 0 */

  xPortSysTickHandler();     /* 转调 FreeRTOS 端口层节拍处理 */

  /* USER CODE BEGIN SysTick_IRQn 1 */

  /* USER CODE END SysTick_IRQn 1 */
}

